"""LLM 工具的「规格」：描述文案、可选值口径、绑定引导语。

▍为什么描述文案要单独放
AstrBot 用 docstring 生成工具的 JSON Schema（``register_llm_tool`` 解析 ``Args:``
段），所以 description 就是喂给模型的**唯一**说明书：模型选不选得中工具、参数填得对不对，
全看这段文字。集中放这里便于统一措辞、也便于中英调整。

▍一个已知限制
``@llm_tool`` 生成的 schema 只支持 ``type`` / ``name`` / ``description``，
**没有 enum**，所以没法在协议层限制取值。对策是：
描述里把候选值列全 + 运行时用别名表容错（见 ``extract.normalize_battle_mode``）。
"""

